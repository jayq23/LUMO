// Map language names to codes  
const languageNameToCode = {
  'English': 'en',
  'Spanish': 'es',
  'French': 'fr',
  'German': 'de',
  'Mandarin': 'zh',
  'Chinese': 'zh',
  'Japanese': 'ja',
  'Korean': 'ko',
  'Russian': 'ru',
  'Arabic': 'ar',
  'Portuguese': 'pt',
  'Tagalog': 'tl',
};

// Normalize language input (convert name to code if needed)
const normalizeLanguage = (lang) => {
  if (!lang) return 'en';
  // If it's already a code (2 characters), return it
  if (lang.length === 2) return lang;
  // Otherwise, convert name to code
  return languageNameToCode[lang] || 'en';
};

// Get translation by key
export const getTranslation = (key, language = 'en', replacements = {}) => {
  const normalizedLang = normalizeLanguage(language);
  const keys = key.split('.');
  let current = translations[normalizedLang] || translations['en'];

  for (const k of keys) {
    current = current?.[k];
    if (!current) {
      console.warn(`Missing translation for key: ${key} in language: ${normalizedLang}`);
      return key; // Fallback to key if not found
    }
  }

  let result = current; 
  for (const [placeholder, value] of Object.entries(replacements)) {
    const regex = new RegExp(`{{${placeholder}}}|{${placeholder}}`, 'g');
    result = result.replace(regex, value);
  }

  return result;
};

// Use in components
export const useTranslation = (language = 'en') => {
  return (key, replacements = {}) => getTranslation(key, language, replacements);
};
